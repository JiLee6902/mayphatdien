import { defineType, defineField } from 'sanity';

export const equipment = defineType({
  name: 'equipment',
  title: 'Thiết bị',
  type: 'document',
  groups: [
    { name: 'content', title: 'Nội dung', default: true },
    { name: 'media', title: 'Hình ảnh' },
    { name: 'seo', title: 'SEO' },
  ],
  fields: [
    defineField({
      name: 'name',
      title: 'Tên thiết bị',
      type: 'string',
      group: 'content',
      description: 'Ví dụ: "Máy phát điện Cummins US 550kVA".',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'slug',
      title: 'Đường dẫn (slug)',
      type: 'slug',
      group: 'content',
      description: 'Tự sinh từ tên. Dùng cho URL /thiet-bi/<slug>. Hạn chế đổi sau khi đã đăng.',
      options: { source: 'name', maxLength: 96 },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'category',
      title: 'Danh mục',
      type: 'reference',
      group: 'content',
      to: [{ type: 'category' }],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'brand',
      title: 'Thương hiệu',
      type: 'string',
      group: 'content',
      description: 'Dùng cho bộ lọc theo hãng, ví dụ "Cummins", "Denyo".',
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: 'power',
      title: 'Công suất / thông số chính',
      type: 'string',
      group: 'content',
      description: 'Chip nổi bật trên thẻ, ví dụ "550 kVA" hoặc "13 bar".',
    }),
    defineField({
      name: 'specs',
      title: 'Bảng thông số kỹ thuật',
      type: 'array',
      group: 'content',
      description: 'Từng dòng gồm nhãn và giá trị, hiển thị ở bảng chi tiết.',
      of: [
        {
          type: 'object',
          fields: [
            defineField({
              name: 'label',
              title: 'Nhãn',
              type: 'string',
              validation: (Rule) => Rule.required(),
            }),
            defineField({
              name: 'value',
              title: 'Giá trị',
              type: 'string',
              validation: (Rule) => Rule.required(),
            }),
          ],
          preview: { select: { title: 'label', subtitle: 'value' } },
        },
      ],
    }),
    defineField({
      name: 'featured',
      title: 'Nổi bật (hiện ở trang chủ)',
      type: 'boolean',
      group: 'content',
      initialValue: false,
    }),
    defineField({
      name: 'description',
      title: 'Mô tả',
      type: 'text',
      group: 'content',
      rows: 4,
    }),
    defineField({
      name: 'images',
      title: 'Thư viện ảnh',
      type: 'array',
      group: 'media',
      description: 'Ảnh đầu tiên là ảnh đại diện. Thêm nhiều góc chụp cho gallery.',
      of: [{ type: 'image', options: { hotspot: true } }],
      options: { layout: 'grid' },
    }),
    defineField({
      name: 'seoDescription',
      title: 'Mô tả SEO',
      type: 'text',
      group: 'seo',
      rows: 3,
      description: 'Meta description cho trang chi tiết (khoảng 150–160 ký tự).',
      validation: (Rule) => Rule.max(180).warning('Nên dưới 160 ký tự.'),
    }),
  ],
  preview: {
    select: { title: 'name', subtitle: 'brand', media: 'images.0' },
  },
});
